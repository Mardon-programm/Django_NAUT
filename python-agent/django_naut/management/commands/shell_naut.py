"""`python manage.py shell_naut` — JSON-RPC notebook shell for DjangoNAUT.

Protocol: one JSON object per line on stdin, one JSON reply per line on
stdout.

Request:   {"id": 1, "type": "exec", "code": "..."}
Response:  {"id": 1, "ok": true, "stdout": "...", "result": ..., "queries": [...]}

Runs code inside a full Django context with every model auto-imported
(like shell_plus), captures stdout and every SQL query generated by the
cell.
"""

import ast
import io
import json
import sys
import traceback

from django.apps import apps
from django.db import connection
from django.test.utils import CaptureQueriesContext

_NAMESPACE = {"__name__": "__djangonaut__"}


def _auto_import_models(namespace):
    try:
        from django.contrib.auth import get_user_model
        namespace["get_user_model"] = get_user_model
    except Exception:
        pass
    try:
        from django.shortcuts import get_object_or_404, get_list_or_404, render, redirect, reverse
        namespace.update({
            "get_object_or_404": get_object_or_404,
            "get_list_or_404": get_list_or_404,
            "render": render,
            "redirect": redirect,
            "reverse": reverse,
        })
    except Exception:
        pass
    for app_config in apps.get_app_configs():
        module = app_config.name
        try:
            __import__(module + ".models")
            models_mod = sys.modules.get(module + ".models")
            if models_mod is not None:
                for name in dir(models_mod):
                    obj = getattr(models_mod, name)
                    if isinstance(obj, type) and getattr(obj, "__module__", "").startswith(module):
                        namespace.setdefault(name, obj)
        except Exception:
            pass


def _to_jsonable(value, depth=0, list_limit=50, dict_limit=50, max_depth=3):
    if value is None or isinstance(value, (bool, int, float, str)):
        return value
    if isinstance(value, (list, tuple, set)):
        if depth > max_depth:
            return "[%d items]" % len(value)
        out = []
        for v in value:
            try:
                out.append(_to_jsonable(v, depth + 1, list_limit, dict_limit, max_depth))
            except Exception:
                out.append(str(v))
        return out[:list_limit]
    if isinstance(value, dict):
        if depth > max_depth:
            return "{...}"
        return {str(k): _to_jsonable(v, depth + 1, list_limit, dict_limit, max_depth) for k, v in list(value.items())[:dict_limit]}
    try:
        import datetime, decimal
        if isinstance(value, datetime.datetime):
            return value.isoformat()
        if isinstance(value, datetime.date):
            return value.isoformat()
        if isinstance(value, decimal.Decimal):
            return str(value)
    except Exception:
        pass
    # Django model instance / queryset
    if hasattr(value, "_meta") and hasattr(value, "_meta"):  # model instance
        try:
            fields = {f.name: getattr(value, f.name) for f in value._meta.fields}
            return {"model": type(value).__name__, "pk": value.pk, **fields}
        except Exception:
            pass
    if hasattr(value, "query") and hasattr(value, "count"):  # queryset
        try:
            rows = []
            for obj in value[:20]:
                if hasattr(obj, "_meta"):
                    rows.append({"model": type(obj).__name__, "pk": obj.pk, **{f.name: getattr(obj, f.name) for f in obj._meta.fields}})
                else:
                    rows.append(_to_jsonable(obj, depth + 1, list_limit, dict_limit, max_depth))
            return {"queryset": type(value).__name__, "total": value.count(), "rows": rows}
        except Exception:
            pass
    try:
        return repr(value)[:2000]
    except Exception:
        return "<unprintable>"


def _exec_code(code, list_limit=50, dict_limit=50, max_depth=3):
    out = io.StringIO()
    old_stdout, old_stderr = sys.stdout, sys.stderr
    sys.stdout, sys.stderr = out, out
    try:
        with CaptureQueriesContext(connection) as ctx:
            try:
                tree = ast.parse(code)
                result = None
                has_result = False
                if tree.body and isinstance(tree.body[-1], ast.Expr):
                    last = tree.body.pop(-1)
                    assign = ast.Assign(
                        targets=[ast.Name(id="__result__", ctx=ast.Store())],
                        value=last.value,
                    )
                    tree.body.append(assign)
                    ast.fix_missing_locations(tree)
                    exec(compile(tree, "<djangonaut>", "exec"), _NAMESPACE)
                    result = _NAMESPACE.get("__result__")
                    has_result = True
                else:
                    exec(compile(tree, "<djangonaut>", "exec"), _NAMESPACE)
            except Exception:
                return {
                    "ok": False,
                    "stdout": out.getvalue(),
                    "error": traceback.format_exc(limit=12),
                    "queries": [],
                }
        return {
            "ok": True,
            "stdout": out.getvalue(),
            "result": _to_jsonable(result, 0, list_limit, dict_limit, max_depth) if has_result else None,
            "hasResult": has_result,
            "queries": [{"sql": q["sql"], "time": q["time"]} for q in ctx.captured_queries],
        }
    finally:
        sys.stdout, sys.stderr = old_stdout, old_stderr


def main():
    import django
    django.setup()
    _auto_import_models(_NAMESPACE)
    try:
        from django.contrib.auth import get_user_model
        _NAMESPACE["User"] = get_user_model()
    except Exception:
        pass
    _NAMESPACE["connection"] = connection

    for line in sys.stdin:
        line = line.strip()
        if not line:
            continue
        try:
            msg = json.loads(line)
        except Exception:
            continue
        rid = msg.get("id")
        if msg.get("type") == "ping":
            sys.stdout.write(json.dumps({"id": rid, "ok": True, "pong": True}) + "\n")
            sys.stdout.flush()
            continue
        if msg.get("type") == "exec":
            limits = msg.get("jsonLimits") or {}
            result = _exec_code(
                msg.get("code", ""),
                int(limits.get("list", 50)),
                int(limits.get("dict", 50)),
                int(limits.get("depth", 3)),
            )
            sys.stdout.write(json.dumps({"id": rid, **result}, default=str) + "\n")
            sys.stdout.flush()
            continue
        sys.stdout.write(json.dumps({"id": rid, "ok": False, "error": "unknown type"}) + "\n")
        sys.stdout.flush()


if __name__ == "__main__":
    main()
